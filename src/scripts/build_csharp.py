"""Build the single-source C# library with embedded WASM and FlatBuffers."""
import argparse
import base64
import re
import sys
from pathlib import Path

from _build_metadata import (
    extract_line_comment_header,
    prepare_source_for_bundle_header,
    render_line_comment_header,
)


def main():
    parser = argparse.ArgumentParser(
        description="Bundle the C# API, FlatBuffers types/runtime, and WASM into build/csharp/LibMP.cs"
    )
    parser.add_argument("--clean", action="store_true", help="Remove the bundled C# output first")
    args = parser.parse_args()

    script_path = Path(__file__).resolve().parent
    project_root = script_path.parent

    build_dir = project_root / "build"
    csharp_source_dir = project_root / "mp_api" / "langs" / "csharp"
    csharp_types_dir = build_dir / "csharp" / "MpTypes"
    wasm_file = build_dir / "wasm" / "LibMpCore.wasm"
    flatbuffers_csharp_dir = project_root / "dependencies" / "flatbuffers_csharp"
    csharp_source_files = sorted(csharp_source_dir.glob("*.cs"))
    api_first_path = csharp_source_dir / "LibMpApi.cs"
    output_file = build_dir / "csharp" / "LibMP.cs"

    if args.clean:
        output_file.unlink(missing_ok=True)
    missing = [path for path in (wasm_file, csharp_types_dir, flatbuffers_csharp_dir) if not path.exists()]
    if missing:
        print("Missing generated input(s): " + ", ".join(str(path) for path in missing), file=sys.stderr)
        print("Run scripts/build.py --csharp.", file=sys.stderr)
        sys.exit(1)

    print("Bundling C# library...")

    # Read WASM and base64 encode
    wasm_bytes = wasm_file.read_bytes()
    wasm_b64 = base64.b64encode(wasm_bytes).decode('ascii')
    print(f"    WASM size: {len(wasm_bytes)} bytes, base64: {len(wasm_b64)} chars")

    # Read FlatBuffers runtime sources
    fb_sources = []
    for cs_file in sorted(flatbuffers_csharp_dir.glob("*.cs")):
        content = cs_file.read_text(encoding="utf-8")
        fb_sources.append(f"// --- {cs_file.name} ---\n{content}")

    # Read generated types
    type_sources = []
    for cs_file in sorted(csharp_types_dir.glob("*.cs")):
        content = cs_file.read_text(encoding="utf-8")
        type_sources.append(f"// --- {cs_file.name} ---\n{content}")

    api_first = api_first_path.read_text(encoding="utf-8")
    api_first = prepare_source_for_bundle_header(api_first)
    local_header_lines, api_first = extract_line_comment_header(api_first, "//")
    bundle_header = render_line_comment_header(
        "//",
        local_header_lines=local_header_lines,
        generated_by="scripts/build_csharp.py",
    )

    # Read LibMP API source files
    api_sources = []
    for cs_file in csharp_source_files:
        content_cs = cs_file.read_text(encoding="utf-8")
        if cs_file == api_first_path:
            content_cs = api_first
        else:
            content_cs = prepare_source_for_bundle_header(content_cs)
        api_sources.append(f"// --- {cs_file.name} ---\n{content_cs}")
    if not fb_sources or not type_sources or not api_sources:
        print("C# source discovery produced an empty input set.", file=sys.stderr)
        sys.exit(1)

    # Collect all using directives and strip them from sources
    all_usings = set()
    # Match using statements: standalone lines or multiple on one line
    using_re = re.compile(r'using\s+(?:global::)?([\w.]+)\s*;')
    using_line_re = re.compile(r'^[;\s]*(using\s+(?:global::)?[\w.]+\s*;\s*)+$', re.MULTILINE)
    auto_gen_re = re.compile(r'^\s*//\s*<auto-generated>.*?//\s*</auto-generated>\s*$', re.MULTILINE | re.DOTALL)

    def strip_usings_and_headers(source):
        """Extract usings and remove source-only headers from bundle fragments."""
        for m in using_re.finditer(source):
            ns = m.group(1)
            all_usings.add(f"using {ns};")
        # Remove all lines that consist entirely of using statements
        source = using_line_re.sub('', source)
        # Also remove individual using statements that might be embedded
        source = re.sub(r'using\s+(?:global::)?[\w.]+\s*;', '', source)
        source = auto_gen_re.sub('', source)
        return source

    # Process all sources
    fb_sources = [strip_usings_and_headers(s) for s in fb_sources]
    type_sources = [strip_usings_and_headers(s) for s in type_sources]
    api_sources = [strip_usings_and_headers(s) for s in api_sources]

    # Build consolidated usings
    sorted_usings = sorted(all_usings)

    # WASM embedding class
    wasm_embed = f"""
namespace LibMP
{{
    public static class EmbeddedWasm
    {{
        private static readonly System.Lazy<byte[]> _bytes =
            new(() => System.Convert.FromBase64String(WasmBase64));

        public static byte[] GetBytes() => _bytes.Value;

        private const string WasmBase64 =
            "{wasm_b64}";
    }}
}}
"""

    # Write output
    output_file.parent.mkdir(parents=True, exist_ok=True)
    # Read defines from Directory.Build.props (single source of truth)
    props_file = project_root / "mp_api" / "langs" / "csharp" / "Directory.Build.props"
    props_defines = []
    if props_file.exists():
        import xml.etree.ElementTree as ET
        tree = ET.parse(props_file)
        for dc in tree.iter("DefineConstants"):
            for d in dc.text.split(";"):
                d = d.strip()
                if d and not d.startswith("$("):
                    props_defines.append(d)

    with open(output_file, "w", encoding="utf-8") as f:
        f.write(bundle_header)
        f.write("\n")

        # Emit defines at file top (from Directory.Build.props)
        for d in props_defines:
            f.write(f"#define {d}\n")
        if props_defines:
            f.write("\n")

        # Write consolidated usings
        exclude_usings = {'using System.Reflection;'}
        for u in sorted_usings:
            if u not in exclude_usings:
                f.write(u + "\n")
        # Resolve ambiguity between Google.FlatBuffers.Table/Struct and Wasmtime.Table
        f.write("using Table = Google.FlatBuffers.Table;\n")
        f.write("using Struct = Google.FlatBuffers.Struct;\n")
        f.write("\n")

        f.write("\n// === SECTION 1: FlatBuffers Runtime ===\n\n")
        f.write("#nullable disable warnings\n\n")
        for src in fb_sources:
            f.write(src)
            f.write("\n")

        f.write("\n// === SECTION 2: Generated Types ===\n\n")
        for src in type_sources:
            f.write(src)
            f.write("\n")

        f.write("\n#nullable restore\n")
        f.write("\n// === SECTION 3: LibMP API ===\n\n")
        for src in api_sources:
            f.write(src)
            f.write("\n")

        f.write("\n// === SECTION 4: Embedded WASM ===\n\n")
        f.write(wasm_embed)

    file_size = output_file.stat().st_size
    print(f"    Success! Bundled: {output_file}")
    print(f"    File size: {file_size:,} bytes ({file_size/1024/1024:.1f} MB)")


if __name__ == "__main__":
    main()
