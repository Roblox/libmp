"""Shared LibMP build metadata readers."""

import re
from pathlib import Path

from _utils import utc_timestamp


PROJECT_ROOT = Path(__file__).resolve().parent.parent
LIBMP_VERSION_HEADER = PROJECT_ROOT / "mp_api" / "control_channel.h"

VERSION_PATTERN = re.compile(
    r"^\s*static constexpr uint32_t\s+(DATA_FORMAT|LIBRARY)\s*=\s*"
    r"Version::BuildFrom\(\s*(\d+)\s*,\s*(\d+)\s*\);",
    re.MULTILINE,
)

DEPENDENCY_NOTICES = {
    "flatbuffers": (
        "FlatBuffers (Apache License 2.0):",
        "https://github.com/Roblox/libmp/blob/HEAD/src/dependencies/flatbuffers/LICENSE",
    ),
    "lz4": (
        "LZ4 (BSD 2-Clause License):",
        "https://github.com/Roblox/libmp/blob/HEAD/src/dependencies/lz4/LICENSE",
    ),
    "spider_runtime": (
        "Spider Luau runtime (Mozilla Public License 2.0):",
        "https://github.com/Roblox/libmp/blob/HEAD/"
        "src/dependencies/spider_runtime/LICENSE",
    ),
}
SHARED_METADATA_PLACEHOLDER = "%LIBMP_SHARED_METADATA%"
SHORT_LICENSE_MARKER = "This file is part of LibMP"


def prepare_source_for_bundle_header(source):
    """Remove a source's short header before adding the full bundle header."""
    lines = source.splitlines(keepends=True)
    marker_lines = [
        index for index, line in enumerate(lines)
        if SHORT_LICENSE_MARKER in line
    ]
    if not marker_lines:
        return source
    if marker_lines != [0] or len(lines) < 2 or lines[1].strip():
        raise RuntimeError(
            "The short license notice must be the first line and followed by "
            "an empty line"
        )
    return "".join(lines[2:])


def read_libmp_versions(version_header=LIBMP_VERSION_HEADER):
    """Return display versions for the LibMP library and payload data format."""
    declarations = VERSION_PATTERN.findall(
        Path(version_header).read_text(encoding="utf-8")
    )
    versions = {
        name: f"{int(major)}.{int(minor)}"
        for name, major, minor in declarations
    }
    expected = {"DATA_FORMAT", "LIBRARY"}
    if set(versions) != expected or len(declarations) != len(expected):
        raise RuntimeError(
            f"Could not read the LibMP library and data-format versions from "
            f"{version_header}"
        )
    return versions


def bundle_metadata_lines(
    version_header=LIBMP_VERSION_HEADER,
    build_timestamp=None,
    bundled_dependencies=("flatbuffers", "lz4"),
    external_dependencies=(),
    *,
    local_header_lines,
    generated_by,
    dependency_source_urls=None,
):
    """Insert common metadata into a language-specific source header."""
    versions = read_libmp_versions(version_header)
    bundled = tuple(bundled_dependencies)
    external = tuple(external_dependencies)
    source_urls = dict(dependency_source_urls or ())
    unknown = set(bundled + external).difference(DEPENDENCY_NOTICES)
    if unknown:
        raise RuntimeError(
            "Unknown dependencies: " + ", ".join(sorted(unknown))
        )
    overlap = set(bundled).intersection(external)
    if overlap:
        raise RuntimeError(
            "Dependencies cannot be both bundled and external: "
            + ", ".join(sorted(overlap))
        )
    unlisted_sources = set(source_urls).difference(bundled + external)
    if unlisted_sources:
        raise RuntimeError(
            "Dependency source URLs require a bundled or external dependency: "
            + ", ".join(sorted(unlisted_sources))
        )

    shared_lines = [
        "https://github.com/Roblox/libmp",
        f"Generated by {generated_by}; DO NOT EDIT.",
        f"Build timestamp: {build_timestamp or utc_timestamp()}",
        f"LibMP library version: {versions['LIBRARY']}",
        f"LibMP data-format version: {versions['DATA_FORMAT']}",
        "",
        "LibMP is distributed under the MIT License:",
        "https://github.com/Roblox/libmp/blob/HEAD/LICENSE",
    ]
    if bundled:
        shared_lines.extend(("", "This bundle includes:"))
        for dependency in bundled:
            description, license_url = DEPENDENCY_NOTICES[dependency]
            shared_lines.extend((f"- {description}", f"  {license_url}"))
            if dependency in source_urls:
                shared_lines.append(f"  {source_urls[dependency]}")
    if external:
        heading = (
            "External dependency:"
            if len(external) == 1
            else "External dependencies:"
        )
        shared_lines.extend(("", heading))
        for dependency in external:
            description, license_url = DEPENDENCY_NOTICES[dependency]
            shared_lines.extend((f"- {description}", f"  {license_url}"))
            if dependency in source_urls:
                shared_lines.append(f"  {source_urls[dependency]}")

    local_lines = tuple(local_header_lines)
    if local_lines.count(SHARED_METADATA_PLACEHOLDER) != 1:
        raise RuntimeError(
            "Language header must contain %LIBMP_SHARED_METADATA% exactly once"
        )
    lines = []
    for line in local_lines:
        if line == SHARED_METADATA_PLACEHOLDER:
            lines.extend(shared_lines)
        else:
            lines.append(line)
    return lines


def extract_line_comment_header(source, comment):
    """Return logical header lines and source following a leading line-comment block."""
    header = []
    offset = 0
    for line in source.splitlines(keepends=True):
        content = line.rstrip("\r\n")
        if content == comment:
            header.append("")
        elif content.startswith(comment + " "):
            header.append(content[len(comment) + 1:])
        else:
            break
        offset += len(line)
    if not header:
        raise RuntimeError("Missing language header")
    return tuple(header), source[offset:].lstrip("\r\n")


def extract_block_comment_header(source):
    """Return logical header lines and source following a leading C-style block."""
    match = re.match(r"\A/\*\n(?P<body>.*?)\n \*/(?:\r?\n)?", source, re.DOTALL)
    if match is None:
        raise RuntimeError("Missing language header")
    header = []
    for line in match.group("body").splitlines():
        if line == " *":
            header.append("")
        elif line.startswith(" * "):
            header.append(line[3:])
        else:
            raise RuntimeError("Malformed block-comment language header")
    return tuple(header), source[match.end():].lstrip("\r\n")


def render_line_comment_header(comment, *args, **kwargs):
    """Render common metadata with a language's line-comment prefix."""
    return "\n".join(
        comment if not line else f"{comment} {line}"
        for line in bundle_metadata_lines(*args, **kwargs)
    ) + "\n"


def render_block_comment_header(*args, preserve=False, **kwargs):
    """Render common metadata as a C-style block comment."""
    opener = "/*!" if preserve else "/*"
    body = "\n".join(
        " *" if not line else f" * {line}"
        for line in bundle_metadata_lines(*args, **kwargs)
    )
    return f"{opener}\n{body}\n */"
