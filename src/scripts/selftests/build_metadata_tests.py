"""Regression tests for shared LibMP build metadata."""

import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import bundle_luau  # noqa: E402
from _build_metadata import (  # noqa: E402
    bundle_metadata_lines,
    extract_block_comment_header,
    extract_line_comment_header,
    read_libmp_versions,
    render_block_comment_header,
    render_line_comment_header,
)

TEST_PACKAGE = {
    "local_header_lines": (
        "LibMP for Test Language",
        "Access Roblox MicroProfiler data from tests.",
        "%LIBMP_SHARED_METADATA%",
        "",
        "Requirements:",
        "- Test runtime.",
        "",
        "Minimal usage:",
        "  run_test()",
    ),
    "generated_by": "scripts/build_test.py",
}


class BuildMetadataTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.header = Path(self.directory.name) / "control_channel.h"
        self.header.write_text(
            "static constexpr uint32_t DATA_FORMAT = "
            "Version::BuildFrom(2, 3);\n"
            "static constexpr uint32_t LIBRARY = "
            "Version::BuildFrom(4, 5);\n",
            encoding="utf-8",
        )

    def test_reads_library_and_data_format_versions(self):
        self.assertEqual(
            read_libmp_versions(self.header),
            {"DATA_FORMAT": "2.3", "LIBRARY": "4.5"},
        )

    def test_renders_common_bundle_metadata(self):
        timestamp = "2000-01-02 03:04:05 UTC"
        lines = bundle_metadata_lines(
            self.header,
            timestamp,
            **TEST_PACKAGE,
        )
        self.assertIn("Build timestamp: " + timestamp, lines)
        self.assertEqual(lines[:3], [
            "LibMP for Test Language",
            "Access Roblox MicroProfiler data from tests.",
            "https://github.com/Roblox/libmp",
        ])
        self.assertIn(
            "Generated by scripts/build_test.py; DO NOT EDIT.", lines
        )
        self.assertIn("LibMP library version: 4.5", lines)
        self.assertIn("LibMP data-format version: 2.3", lines)
        self.assertIn(
            "https://github.com/Roblox/libmp/blob/HEAD/LICENSE", lines
        )
        self.assertIn("- FlatBuffers (Apache License 2.0):", lines)
        self.assertIn("- LZ4 (BSD 2-Clause License):", lines)
        self.assertIn("Requirements:", lines)
        self.assertIn("  run_test()", lines)
        self.assertNotIn("%LIBMP_SHARED_METADATA%", lines)
        self.assertTrue(
            render_line_comment_header(
                "#", self.header, timestamp, **TEST_PACKAGE
            ).startswith("# LibMP for Test Language")
        )
        self.assertTrue(
            render_block_comment_header(
                self.header, timestamp, preserve=True, **TEST_PACKAGE
            ).startswith("/*!\n")
        )

    def test_extracts_line_comment_language_header(self):
        lines, source = extract_line_comment_header(
            "# LibMP for Python\n# %LIBMP_SHARED_METADATA%\n#\n\nvalue = 1\n",
            "#",
        )
        self.assertEqual(lines, ("LibMP for Python", "%LIBMP_SHARED_METADATA%", ""))
        self.assertEqual(source, "value = 1\n")

    def test_extracts_block_comment_language_header(self):
        lines, source = extract_block_comment_header(
            "/*\n * LibMP for JavaScript\n * %LIBMP_SHARED_METADATA%\n */\n\nlet x = 1;\n"
        )
        self.assertEqual(
            lines, ("LibMP for JavaScript", "%LIBMP_SHARED_METADATA%")
        )
        self.assertEqual(source, "let x = 1;\n")

    def test_dependency_notices_match_bundled_dependencies(self):
        lines = bundle_metadata_lines(
            self.header,
            "2000-01-02 03:04:05 UTC",
            bundled_dependencies=("lz4",),
            **TEST_PACKAGE,
        )
        text = "\n".join(lines)
        self.assertNotIn("FlatBuffers", text)
        self.assertIn("LZ4 (BSD 2-Clause License)", text)

    def test_external_dependency_notices_are_separate_from_bundled_ones(self):
        lines = bundle_metadata_lines(
            self.header,
            "2000-01-02 03:04:05 UTC",
            bundled_dependencies=("flatbuffers",),
            external_dependencies=("lz4",),
            **TEST_PACKAGE,
        )
        text = "\n".join(lines)
        self.assertIn("This bundle includes:\n- FlatBuffers", text)
        self.assertIn("External dependency:\n- LZ4", text)
        self.assertEqual(text.count("LZ4 (BSD 2-Clause License)"), 1)

    def test_dependency_notice_can_link_original_source(self):
        source_url = (
            "https://github.com/example/dependency/tree/revision/runtime"
        )
        lines = bundle_metadata_lines(
            self.header,
            "2000-01-02 03:04:05 UTC",
            bundled_dependencies=("spider_runtime",),
            dependency_source_urls={"spider_runtime": source_url},
            **TEST_PACKAGE,
        )
        text = "\n".join(lines)
        self.assertIn("Spider Luau runtime (Mozilla Public License 2.0)", text)
        self.assertIn("src/dependencies/spider_runtime/LICENSE", text)
        self.assertIn("\n  " + source_url, text)
        self.assertNotIn("Original source:", text)

    def test_luau_header_links_configured_spider_runtime_revision(self):
        header = bundle_luau.render_bundle_header(
            TEST_PACKAGE["local_header_lines"],
            "2000-01-02 03:04:05 UTC",
            {
                "repo": "https://github.com/SovereignSatellite/Spider.git",
                "commit": "abc123",
                "branch": "stable",
            },
        )
        self.assertIn("Spider Luau runtime (Mozilla Public License 2.0)", header)
        self.assertIn(
            "https://github.com/SovereignSatellite/Spider/tree/abc123/"
            "Targets/Luau/Printer/runtime",
            header,
        )
        self.assertEqual(
            bundle_luau.spider_runtime_source_url({
                "repo": "https://github.com/SovereignSatellite/Spider.git",
                "branch": "stable",
            }),
            "https://github.com/SovereignSatellite/Spider/tree/stable/"
            "Targets/Luau/Printer/runtime",
        )

    def test_dependency_cannot_be_bundled_and_external(self):
        with self.assertRaisesRegex(RuntimeError, "both bundled and external"):
            bundle_metadata_lines(
                self.header,
                bundled_dependencies=("lz4",),
                external_dependencies=("lz4",),
                **TEST_PACKAGE,
            )


if __name__ == "__main__":
    unittest.main()
