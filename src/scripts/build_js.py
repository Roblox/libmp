"""Build the self-contained browser/Node LibMP JavaScript library."""

import argparse
import base64
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

from _build_metadata import (
    extract_block_comment_header,
    prepare_source_for_bundle_header,
    render_block_comment_header,
)
from _utils import load_build_config


def render_bundle_header(entry_path, build_timestamp=None):
    source = Path(entry_path).read_text(encoding="utf-8")
    source = prepare_source_for_bundle_header(source)
    local_header_lines, _ = extract_block_comment_header(source)
    return render_block_comment_header(
        build_timestamp=build_timestamp,
        local_header_lines=local_header_lines,
        generated_by="scripts/build_js.py",
        preserve=True,
    )


def run(command, **kwargs):
    print("  >", " ".join(str(item) for item in command), flush=True)
    result = subprocess.run([str(item) for item in command], **kwargs)
    if result.returncode != 0:
        sys.exit(result.returncode)


def ensure_js_tools(project_root, npm_version, esbuild_version):
    tools_dir = project_root / "build" / "utils" / "js_tools"
    esbuild = tools_dir / "node_modules" / ".bin" / ("esbuild.cmd" if sys.platform == "win32" else "esbuild")
    marker = tools_dir / "versions.json"
    expected = {"esbuild": esbuild_version, "flatbuffers": npm_version}
    if esbuild.exists() and marker.exists():
        try:
            if json.loads(marker.read_text(encoding="utf-8")) == expected:
                return tools_dir, esbuild
        except (OSError, json.JSONDecodeError):
            pass

    if tools_dir.exists():
        shutil.rmtree(tools_dir)
    tools_dir.mkdir(parents=True)
    npm = shutil.which("npm")
    if npm is None:
        print("npm is required to install the pinned JavaScript build tools.", file=sys.stderr)
        sys.exit(1)
    run([
        npm, "install", "--prefix", tools_dir, "--no-save", "--no-package-lock",
        f"esbuild@{esbuild_version}", f"flatbuffers@{npm_version}",
    ])
    marker.write_text(json.dumps(expected, indent=2) + "\n", encoding="utf-8")
    return tools_dir, esbuild


def main():
    parser = argparse.ArgumentParser(
        description="Bundle the JS API, FlatBuffers types/runtime, and WASM into build/js/LibMP.js"
    )
    parser.add_argument("--clean", action="store_true", help="Remove JS outputs first; cached tools are preserved")
    args = parser.parse_args()

    project_root = Path(__file__).resolve().parent.parent
    build_dir = project_root / "build" / "js"
    wasm_path = project_root / "build" / "wasm" / "LibMpCore.wasm"
    entry_path = project_root / "mp_api" / "langs" / "js" / "libmp_api.js"
    version_path = project_root / "dependencies" / "flatbuffers_version.txt"
    output_path = build_dir / "LibMP.js"
    embedded_wasm_path = build_dir / "embedded_wasm.js"

    if args.clean and build_dir.exists():
        for path in (output_path, embedded_wasm_path):
            path.unlink(missing_ok=True)
    if not wasm_path.exists():
        print(f"Missing WASM input: {wasm_path}", file=sys.stderr)
        print("Run scripts/build_wasm.py first.", file=sys.stderr)
        sys.exit(1)

    version_config = json.loads(version_path.read_text(encoding="utf-8"))
    npm_version = version_config["npm_version"]
    build_config = load_build_config()
    esbuild_version = build_config["esbuild"]["version"]
    tools_dir, esbuild = ensure_js_tools(project_root, npm_version, esbuild_version)
    bundle_header = render_bundle_header(entry_path)

    build_dir.mkdir(parents=True, exist_ok=True)
    encoded_wasm = base64.b64encode(wasm_path.read_bytes()).decode("ascii")
    embedded_wasm_path.write_text(
        "// Generated by scripts/build_js.py.\n"
        f"export const LIBMP_WASM_BASE64 = {json.dumps(encoded_wasm)};\n",
        encoding="utf-8",
    )

    env = os.environ.copy()
    env["NODE_PATH"] = str(tools_dir / "node_modules")
    # esbuild labels bundled modules with paths relative to its working directory;
    # run it from the repository root so the output doesn't depend on the caller's.
    run([
        esbuild,
        entry_path,
        "--bundle",
        "--format=iife",
        "--global-name=LibMP",
        "--platform=browser",
        "--target=es2020",
        "--external:node:fs",
        "--external:node:fs/promises",
        f"--banner:js={bundle_header}",
        "--footer:js=if(typeof module!==\"undefined\"&&module.exports)module.exports=LibMP;",
        f"--outfile={output_path}",
    ], env=env, cwd=project_root.parent)
    print(f"Success: {output_path} ({output_path.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
