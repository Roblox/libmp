// extract_capture.cpp -- offline extractor for the CaptureBuilder round-trip test.
//
// Reads a REAL .gprx profiler dump through LibMP and emits a
// self-contained C++ header (src/tests/cpp/roundtrip_capture_data.inc) holding the data
// needed to rebuild an equivalent in-memory capture in capture_roundtrip_tests.cpp.
// This lets the round-trip test prove the create->consume pipeline against real
// profiler data without committing any binary dump.
//
// Run once by a developer (not part of the build). Legacy v1 global indexes with
// 32-bit data offsets are accepted by default; do not disable that compatibility
// when processing a dump which requires it. From the repo root:
//
//   python3 src/scripts/build_native.py
//   g++ -std=c++17 \
//       -Isrc -Isrc/dependencies src/tests/tools/extract_capture.cpp \
//       src/build/native/libmp.a -o /tmp/extract_capture
//   /tmp/extract_capture <dump.gprx> > src/tests/cpp/roundtrip_capture_data.inc
//
// Frame timestamps and raw thread-log entries are copied bit-for-bit. Only scope ticks
// inside raw log entries are intrinsically limited to 48 bits by the entry format.

#include "mp_api/cpp_api.h"
#include "gprx_container/container_context.h"

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

namespace
{
constexpr uint32_t kMaxFrames = 16;
// Cap only the volume-heavy per-frame sample data so the committed .inc stays small.
// All descriptors (threads/groups/timers/counters) are emitted in full.
constexpr uint32_t kMaxCountersForSamples = 32;

struct ThreadLogRow
{
    uint32_t threadId;
    uint32_t entryOffset;
    uint32_t entryCount;
    bool isRemoved;
};

std::string CppEscape(const char* s)
{
    std::string out;
    if (!s)
        return out;
    for (const unsigned char* p = reinterpret_cast<const unsigned char*>(s); *p; ++p)
    {
        unsigned char c = *p;
        if (c == '\\' || c == '"')
        {
            out.push_back('\\');
            out.push_back(static_cast<char>(c));
        }
        else if (c >= 0x20 && c < 0x7f)
        {
            out.push_back(static_cast<char>(c));
        }
        else
        {
            char buf[8];
            std::snprintf(buf, sizeof buf, "\\%03o", c);
            out += buf;
        }
    }
    return out;
}

// C++17 hexadecimal floating literal -> exact bit round-trip for finite values.
std::string HexFloat(double v)
{
    if (!std::isfinite(v))
        return std::string("0.0 /* non-finite in dump, coerced */");
    char buf[64];
    std::snprintf(buf, sizeof buf, "%a", v);
    return std::string(buf);
}
} // namespace

int main(int argc, char** argv)
{
    if (argc < 2)
    {
        std::fprintf(stderr, "usage: %s <dump.gprx>\n", argv[0]);
        return 2;
    }

    LibMP::Init();

    auto s = LibMP::Session::OpenFromFile(argv[1]);
    if (!s || !s->IsValid())
    {
        std::fprintf(stderr, "failed to open or validate dump: %s\n", argv[1]);
        return 1;
    }

    FILE* out = stdout;

    std::fprintf(out,
        "// roundtrip_capture_data.inc -- GENERATED by src/tests/tools/extract_capture.cpp.\n"
        "// DO NOT EDIT BY HAND. Regenerate with the command in that tool's header.\n"
        "//\n"
        "// Real profiler data extracted from a .gprx dump. Frame timestamps and raw\n"
        "// per-thread log entries are preserved bit-for-bit.\n"
        "#pragma once\n"
        "#include <cstdint>\n\n"
        "namespace roundtrip_data\n{\n\n");

    // -------- Threads --------
    auto threadIds = s->GetThreadIds();
    std::fprintf(out, "struct ThreadRow { uint32_t id; const char* name; uint32_t buffer_size; bool is_gpu; };\n");
    std::fprintf(out, "static const ThreadRow kThreads[] = {\n");
    uint32_t threadCount = 0;
    for (mpsize_t i = 0; i < threadIds.Size(); ++i)
    {
        uint32_t tid = threadIds[i];
        const auto* d = s->GetThreadDesc(tid);
        if (!d)
            continue;
        const char* nm = d->thread_name() ? d->thread_name()->c_str() : "";
        std::fprintf(out, "    { %uu, \"%s\", %uu, %s },\n",
            tid, CppEscape(nm).c_str(), d->buffer_size(), d->is_gpu() ? "true" : "false");
        ++threadCount;
    }
    std::fprintf(out, "};\n");
    std::fprintf(out, "static const uint32_t kThreadIdGpu = %uu;\n\n", s->GetThreadIdGpu());

    // -------- Groups --------
    uint32_t groupIdMax = s->GetGroupIdMax();
    std::fprintf(out, "struct GroupRow { uint32_t id; const char* name; uint32_t color; bool is_gpu; };\n");
    std::fprintf(out, "static const GroupRow kGroups[] = {\n");
    uint32_t groupCount = 0;
    for (uint32_t gid = 1; gid <= groupIdMax; ++gid)
    {
        const auto* d = s->GetGroupDesc(gid);
        if (!d)
            continue;
        const char* nm = d->group_name() ? d->group_name()->c_str() : "";
        std::fprintf(out, "    { %uu, \"%s\", 0x%08xu, %s },\n", gid, CppEscape(nm).c_str(), d->color(),
            d->is_gpu() ? "true" : "false");
        ++groupCount;
    }
    std::fprintf(out, "};\n");
    std::fprintf(out, "static const uint32_t kGroupIdMax = %uu;\n\n", groupIdMax);

    // -------- Timers --------
    auto timerIds = s->GetTimerIds();
    std::fprintf(out, "struct TimerRow { uint32_t id; const char* name; uint32_t group_id; uint32_t color; bool is_user_timer; };\n");
    std::fprintf(out, "static const TimerRow kTimers[] = {\n");
    uint32_t timerCount = 0;
    for (mpsize_t i = 0; i < timerIds.Size(); ++i)
    {
        uint32_t tid = timerIds[i];
        const auto* d = s->GetTimerDesc(tid);
        if (!d)
            continue;
        const char* nm = d->timer_name() ? d->timer_name()->c_str() : "";
        std::fprintf(out, "    { %uu, \"%s\", %uu, 0x%08xu, %s },\n", tid, CppEscape(nm).c_str(), d->group_id(),
            d->color(), d->is_user_timer() ? "true" : "false");
        ++timerCount;
    }
    std::fprintf(out, "};\n\n");

    // -------- Counters --------
    auto counterIds = s->GetCounterIds();
    std::fprintf(out, "struct CounterRow { uint32_t id; const char* name; uint32_t parent; uint32_t sibling; uint32_t first_child; uint32_t level; };\n");
    std::fprintf(out, "static const CounterRow kCounters[] = {\n");
    std::vector<uint32_t> counterIdList;
    for (mpsize_t i = 0; i < counterIds.Size(); ++i)
    {
        uint32_t cid = counterIds[i];
        const auto* d = s->GetCounterDesc(cid);
        if (!d)
            continue;
        const char* nm = d->counter_name() ? d->counter_name()->c_str() : "";
        std::fprintf(out, "    { %uu, \"%s\", %uu, %uu, %uu, %uu },\n", cid, CppEscape(nm).c_str(), d->parent(),
            d->sibling(), d->first_child(), static_cast<uint32_t>(d->level()));
        counterIdList.push_back(cid);
    }
    std::fprintf(out, "};\n\n");

    // -------- GlobalDesc --------
    const auto* gd = s->GetGlobalDesc();
    float toMsCpu = gd ? gd->tick_to_ms_cpu() : 0.0f;
    float toMsGpu = gd ? gd->tick_to_ms_gpu() : 0.0f;
    std::fprintf(out, "static const float kGlobalTickToMsCpu = %s;\n", HexFloat(toMsCpu).c_str());
    std::fprintf(out, "static const float kGlobalTickToMsGpu = %s;\n\n", HexFloat(toMsGpu).c_str());

    // -------- GeneralInfo --------
    const auto* generalInfo = s->GetGeneralInfo();
    const auto* platformInfo = generalInfo ? generalInfo->platform_info_json() : nullptr;
    std::fprintf(out, "static const bool kHasGeneralInfo = %s;\n", generalInfo ? "true" : "false");
    std::fprintf(out, "static const bool kHasPlatformInfoJson = %s;\n", platformInfo ? "true" : "false");
    std::fprintf(out, "static const char kPlatformInfoJson[] = \"%s\";\n\n",
        CppEscape(platformInfo ? platformInfo->c_str() : "").c_str());

    // -------- Frames --------
    uint32_t frameIdMin = s->GetFrameIdMin();
    uint32_t frameIdMax = s->GetFrameIdMax();
    uint32_t availFrames = (frameIdMax >= frameIdMin) ? (frameIdMax - frameIdMin + 1) : 0;
    uint32_t numFrames = availFrames < kMaxFrames ? availFrames : kMaxFrames;
    std::vector<uint64_t> logEntries;
    std::vector<ThreadLogRow> threadLogs;
    GPRX::ContainerContext* container = MpGetContainerFromSession(s->GetHandle());
    if (!container)
    {
        std::fprintf(stderr, "failed to access the dump container\n");
        return 1;
    }

    std::fprintf(out, "// Exact 64-bit frame ticks from the source dump.\n");
    std::fprintf(out, "struct FrameRow { uint32_t frame_index; uint32_t absolute_id; uint64_t tsc_start; uint64_t tsc_end; uint64_t tsg_start; uint64_t tsg_end; uint64_t label_offset_min; uint64_t label_offset_max; bool paused; bool incomplete; uint32_t thread_log_offset; uint32_t thread_log_count; };\n");
    std::fprintf(out, "static const FrameRow kFrames[] = {\n");
    for (uint32_t i = 0; i < numFrames; ++i)
    {
        uint32_t fid = frameIdMin + i;
        auto frame = s->FetchFrameDesc(fid);
        if (!frame)
        {
            std::fprintf(stderr, "missing frame desc for frame_id %u\n", fid);
            return 1;
        }
        if (threadLogs.size() > GPRX::max_u32)
        {
            std::fprintf(stderr, "thread-log fixture exceeds uint32_t offsets\n");
            return 1;
        }
        const uint32_t threadLogOffset = static_cast<uint32_t>(threadLogs.size());

        for (const auto& threadLog : frame->thread_logs)
        {
            const uint32_t entryCount = threadLog.log_entries_num();
            if (logEntries.size() > GPRX::max_u32)
            {
                std::fprintf(stderr, "thread-log fixture exceeds uint32_t offsets\n");
                return 1;
            }

            const uint32_t entryOffset = static_cast<uint32_t>(logEntries.size());
            if (entryCount > GPRX::max_u32 - entryOffset)
            {
                std::fprintf(stderr, "thread-log fixture exceeds uint32_t offsets\n");
                return 1;
            }
            if (entryCount)
            {
                if (entryCount > GPRX::max_mpsize_t / sizeof(uint64_t))
                {
                    std::fprintf(stderr, "thread log is too large: frame=%u thread=%u entries=%u\n",
                        fid, threadLog.thread_id(), entryCount);
                    return 1;
                }

                std::vector<uint64_t> copiedEntries(entryCount);
                bool copied = false;
                const bool locked = s->WithDataLock([&] {
                    GPRX::Locator locator;
                    locator.entry = threadLog.log_start_locator();
                    mpsize_t bytes = entryCount * sizeof(uint64_t);
                    mpsize_t readyBytes = 0;
                    const uint8_t* data = container->GetDataByLocator(
                        locator, GPRX::ContainerContext::TypeOfData::Default, &bytes, &readyBytes);
                    if (data && bytes == entryCount * sizeof(uint64_t) && readyBytes >= bytes)
                    {
                        std::memcpy(copiedEntries.data(), data, bytes);
                        copied = true;
                    }
                });
                if (!locked || !copied)
                {
                    std::fprintf(stderr, "failed to copy thread log: frame=%u thread=%u entries=%u removed=%u\n",
                        fid, threadLog.thread_id(), entryCount, threadLog.is_removed() ? 1u : 0u);
                    return 1;
                }
                logEntries.insert(logEntries.end(), copiedEntries.begin(), copiedEntries.end());
            }

            threadLogs.push_back({threadLog.thread_id(), entryOffset, entryCount, threadLog.is_removed()});
        }

        const size_t threadLogCount = threadLogs.size() - threadLogOffset;
        if (threadLogCount > GPRX::max_u32)
        {
            std::fprintf(stderr, "frame has too many thread logs: frame=%u\n", fid);
            return 1;
        }
        std::fprintf(out,
            "    { %uu, %uu, 0x%016llxull, 0x%016llxull, 0x%016llxull, 0x%016llxull, "
            "0x%016llxull, 0x%016llxull, %s, %s, %uu, %uu },\n",
            i, frame->frame_absolute_id,
            (unsigned long long)frame->tick_start_cpu,
            (unsigned long long)frame->tick_end_cpu,
            (unsigned long long)frame->tick_start_gpu,
            (unsigned long long)frame->tick_end_gpu,
            (unsigned long long)frame->label_offset_min,
            (unsigned long long)frame->label_offset_max,
            frame->is_paused ? "true" : "false",
            frame->is_incomplete ? "true" : "false",
            threadLogOffset, static_cast<uint32_t>(threadLogCount));
    }
    std::fprintf(out, "};\n\n");

    // -------- Counter samples (per counter per frame index) --------
    std::fprintf(out, "struct CounterSampleRow { uint32_t counter_id; uint32_t frame_index; double value; };\n");
    std::fprintf(out, "static const CounterSampleRow kCounterSamples[] = {\n");
    uint32_t counterSampleCount = 0;
    uint32_t countersSampled = 0;
    bool counterSamplesCapped = false;
    for (uint32_t cid : counterIdList)
    {
        if (countersSampled >= kMaxCountersForSamples)
        {
            counterSamplesCapped = true;
            break;
        }
        ++countersSampled;
        auto samples = s->GetCounterSamples(cid);
        for (uint32_t i = 0; i < numFrames; ++i)
        {
            uint32_t fid = frameIdMin + i;
            const auto* smp = samples.GetSampleByFrameId(fid);
            if (!smp)
                continue;
            std::fprintf(out, "    { %uu, %uu, %s },\n", cid, i, HexFloat(smp->value()).c_str());
            ++counterSampleCount;
        }
    }
    std::fprintf(out, "};\n");
    if (counterSamplesCapped)
        std::fprintf(out, "// note: counter samples capped to the first %u counters (of %zu).\n",
            kMaxCountersForSamples, counterIdList.size());
    std::fprintf(out, "static const bool kHasCounterSamples = %s;\n\n", counterSampleCount ? "true" : "false");

    auto writeU64Samples = [&](const char* rowName, const char* arrayName, auto samples) {
        std::fprintf(out, "struct %s { uint32_t frame_index; uint64_t value; };\n", rowName);
        std::fprintf(out, "static const %s %s[] = {\n", rowName, arrayName);
        for (mpsize_t index = 0; index < samples.Size(); ++index)
        {
            const auto* sample = samples.Get(index);
            if (!sample || sample->frame_id() < frameIdMin || sample->frame_id() >= frameIdMin + numFrames)
                continue;
            std::fprintf(out, "    { %uu, 0x%016llxull },\n",
                sample->frame_id() - frameIdMin, (unsigned long long)sample->value());
        }
        std::fprintf(out, "};\n\n");
    };
    writeU64Samples("PlaceIdSampleRow", "kPlaceIdSamples", s->GetPlaceIdSamples());
    writeU64Samples("UtcTimestampSampleRow", "kUtcTimestampSamples", s->GetUtcTimestampSamples());

    // -------- Exact raw per-thread logs --------
    std::fprintf(out, "// Exact uint64_t entries, flattened in frame/thread-log order.\n");
    std::fprintf(out, "static const uint64_t kThreadLogEntries[] = {\n");
    for (size_t i = 0; i < logEntries.size(); ++i)
    {
        if ((i % 4) == 0)
            std::fprintf(out, "    ");
        std::fprintf(out, "0x%016llxull,%s", (unsigned long long)logEntries[i],
            (i % 4) == 3 || i + 1 == logEntries.size() ? "\n" : " ");
    }
    std::fprintf(out, "};\n");
    std::fprintf(out, "\nstruct ThreadLogRow { uint32_t thread_id; uint32_t entry_offset; uint32_t entry_count; bool is_removed; };\n");
    std::fprintf(out, "static const ThreadLogRow kThreadLogs[] = {\n");
    for (const auto& row : threadLogs)
    {
        std::fprintf(out, "    { %uu, %uu, %uu, %s },\n",
            row.threadId, row.entryOffset, row.entryCount, row.isRemoved ? "true" : "false");
    }
    std::fprintf(out, "};\n");
    std::fprintf(out, "\nstatic const uint32_t kNumFramesExtracted = %uu;\n", numFrames);
    std::fprintf(out, "\n} // namespace roundtrip_data\n");

    std::fprintf(stderr,
        "extracted: threads=%u groups=%u timers=%u counters=%zu frames=%u counter_samples=%u "
        "thread_logs=%zu log_entries=%zu\n",
        threadCount, groupCount, timerCount, counterIdList.size(), numFrames, counterSampleCount,
        threadLogs.size(), logEntries.size());
    std::fprintf(stderr, "frameIdMin=%u frameIdMax=%u avail=%u\n", frameIdMin, frameIdMax, availFrames);

    return 0;
}
